// Walk the player-facing flow: title -> options -> controls -> chapter select -> play ch1 -> click to begin -> pause -> resume.
import { launch, shot } from './harness.mjs';
const { browser, page, errors } = await launch({ url: 'http://localhost:5173/' });
page.on('pageerror', (e) => console.log('[pageerror]', e.message, (e.stack || '').split('\n').slice(0, 3).join(' | ')));
const clickText = async (txt) => { const b = page.locator('button', { hasText: txt }).first(); await b.click(); await page.waitForTimeout(400); };
await page.waitForFunction(() => window.__ready, null, { timeout: 60000 });
await page.waitForTimeout(800);
await shot(page, 'ui_01_title');
await clickText('OPTIONS'); await shot(page, 'ui_02_options'); await clickText('BACK');
await clickText('CONTROLS'); await shot(page, 'ui_03_controls'); await clickText('BACK');
await clickText('DIFFICULTY'); await clickText('DIFFICULTY'); await clickText('DIFFICULTY'); await clickText('DIFFICULTY');
console.log('difficulty after 4 clicks:', await page.evaluate(() => window.__game.settings.get('difficulty')));
await clickText('CHAPTER SELECT'); await shot(page, 'ui_04_chapters');
await page.locator('.chap').first().click();
await page.waitForTimeout(1500);
await shot(page, 'ui_05_loading');
await page.waitForFunction(() => document.querySelector('.click'), null, { timeout: 120000 });
await shot(page, 'ui_06_click_to_begin');
await page.mouse.click(480, 300);
await page.waitForTimeout(2500);
console.log('state after click:', await page.evaluate(() => window.__game.state));
await shot(page, 'ui_07_ingame');
await page.waitForTimeout(6000);
await shot(page, 'ui_08_intro');
await page.keyboard.press('Escape');
await page.waitForTimeout(600);
console.log('state after esc:', await page.evaluate(() => window.__game.state));
await shot(page, 'ui_09_pause');
await clickText('RESUME');
console.log('state after resume:', await page.evaluate(() => window.__game.state));
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
await clickText('QUIT TO MENU');
console.log('state after quit:', await page.evaluate(() => window.__game.state));
await shot(page, 'ui_10_back_to_title');
console.log('errors:', errors.filter((e) => !e.includes('Failed to load')).slice(0, 8).join('\n') || 'none');
await browser.close();
