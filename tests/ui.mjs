// Usage: node tests/ui.mjs <outDir> [w h]
// Screenshots every UI state: title, live HUD (bot), pause, settings tabs, controls, results.
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const [outDir = 'tests/out/ui', w = '1280', h = '720'] = process.argv.slice(2);
const base = process.env.BASE_URL ?? 'http://localhost:5173/';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: Number(w), height: Number(h) } });
page.on('pageerror', (e) => console.log(`[pageerror] ${e.message}`));
page.on('console', (m) => { if (m.type() === 'error') console.log(`[error] ${m.text()}`); });
const shot = async (name) => { await page.screenshot({ path: `${outDir}/${name}.png` }); console.log('shot', name); };
await page.goto(base, { waitUntil: 'load' });
await page.waitForFunction(() => window.__ready === true, null, { timeout: 120000 });
await page.waitForTimeout(1500);
await shot('t_title');
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(300);
await shot('t_title_nav');
await page.goto(base + '?bot=1&god=1', { waitUntil: 'load' });
await page.waitForFunction(() => window.__ready === true, null, { timeout: 120000 });
await page.waitForTimeout(3500);
await shot('t_banner');
await page.waitForTimeout(9000);
await shot('t_hud');
await page.evaluate(() => { const g = window.game; g.player.hp = 22; g.hud.damageFrom(g.player.x + 3, g.player.z); g.hud.toast('PERFECT COUNTER', '#ffd24a'); g.hud.feed('THUG DOWN', '+240'); });
await page.waitForTimeout(250);
await shot('t_hud_low');
await page.evaluate(() => { window.game.preStep = null; window.game.setPaused(true); });
await page.waitForTimeout(600);
await shot('t_pause');
await page.evaluate(() => window.game.hud.openSettings('pause'));
await page.waitForTimeout(500);
await shot('t_settings');
await page.evaluate(() => { const b = [...document.querySelectorAll('.tabs button')].find((x) => x.textContent === 'AUDIO'); b?.click(); });
await page.waitForTimeout(300);
await shot('t_settings_audio');
await page.evaluate(() => window.game.hud.show('controls'));
await page.waitForTimeout(1200);
await shot('t_controls');
await page.evaluate(() => window.game.hud.gameOver({ 'Wave reached': 9, Score: '48,210', Kills: 61, 'Bodies on the floor': 61, 'Best combo': 37, Counters: '22 (9 perfect)', Dodges: '14 (3 perfect)', Finishers: 18, Takedowns: 6, 'Environment kills': 3, 'Bones broken': 25, Disarms: 4 }, { grade: 'A', record: true }));
await page.waitForTimeout(1500);
await shot('t_results');
// spectate: the run is over, fly round the room (the button on the results)
await page.evaluate(() => {
  const g = window.game;
  g.over = true;
  g.paused = false;
  const b = [...document.querySelectorAll('#gocol .mlist button')].find((x) => x.textContent.includes('SPECTATE'));
  b?.click();
});
await page.waitForTimeout(900);
await shot('t_spectate');
await page.keyboard.press('Escape');
await page.waitForTimeout(700);
await shot('t_spectate_back');
await browser.close();
