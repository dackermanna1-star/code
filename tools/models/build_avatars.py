"""Convert the Rocketbox avatars listed in avatars.json into the game's assets and index.

For each avatar: checks its FBX and textures out of a local clone of the Rocketbox library (a
blobless clone fetches only those files), converts the mesh (rocketbox.mjs) and writes its
textures (avatar_textures.py) into src/character/models/<id>/; then writes
src/character/models/avatars.ts, the index realBody.ts imports.

Usage: python3 -I tools/models/build_avatars.py <Microsoft-Rocketbox clone> [id ...]
"""
import json
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
HERE = os.path.join(ROOT, 'tools', 'models')
MODELS = os.path.join(ROOT, 'src', 'character', 'models')
sys.path.insert(0, HERE)
import avatar_textures  # noqa: E402


def run(cmd, cwd=None):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f'{cmd[0]} failed: {r.stderr[-2000:]}')
    return r.stdout


def main(clone, only):
    manifest = json.load(open(os.path.join(HERE, 'avatars.json')))['avatars']
    tmp = os.path.join(clone, '.game_labels')
    os.makedirs(tmp, exist_ok=True)
    for aid, a in manifest.items():
        if only and aid not in only:
            continue
        rel = 'Assets/Avatars/' + a['src']
        name = os.path.basename(a['src'])
        files = run(['git', 'ls-tree', '-r', 'HEAD', '--name-only', '--', rel], cwd=clone).split()
        want = [f for f in files if f.endswith(f'/Export/{name}.fbx') or ('/Textures/' in f and f.endswith('.tga'))]
        run(['git', '-c', 'advice.detachedHead=false', 'checkout', 'HEAD', '--'] + want, cwd=clone)
        out = os.path.join(MODELS, aid)
        os.makedirs(out, exist_ok=True)
        labels = os.path.join(tmp, aid + '.json')
        print(aid, run(['node', os.path.join(HERE, 'rocketbox.mjs'), os.path.join(clone, rel, 'Export', name + '.fbx'), os.path.join(out, 'mesh.json'), labels], cwd=ROOT).strip().splitlines()[-1])
        avatar_textures.main(os.path.join(clone, rel, 'Textures'), labels, out, a)
    write_index(manifest)


def write_index(manifest):
    lines = [
        '// Generated by tools/models/build_avatars.py from tools/models/avatars.json - do not edit.',
        '// Microsoft Rocketbox avatars (MIT): https://github.com/microsoft/Microsoft-Rocketbox',
        "import type { AvatarAsset } from '../realBody';",
    ]
    entries = []
    for i, (aid, a) in enumerate(manifest.items()):
        d = os.path.join(MODELS, aid)
        if not os.path.exists(os.path.join(d, 'mesh.json')):
            continue
        v = f'a{i}'
        lines.append(f"import {v}m from './{aid}/mesh.json';")
        for t, f in (('b', 'body.jpg'), ('bn', 'body_n.jpg'), ('bf', 'body_f.png'), ('h', 'head.jpg'), ('hf', 'head_f.png')):
            lines.append(f"import {v}{t} from './{aid}/{f}';")
        hair = os.path.exists(os.path.join(d, 'hair.webp'))
        if hair:
            lines.append(f"import {v}r from './{aid}/hair.webp';")
        entries.append(f"  {aid}: {{ src: '{os.path.basename(a['src'])}', mesh: {v}m as unknown as AvatarAsset['mesh'], body: {v}b, bodyN: {v}bn, bodyF: {v}bf, head: {v}h, headF: {v}hf, hair: {v + 'r' if hair else 'null'} }},")
    lines.append('')
    lines.append('export const AVATARS: Record<string, AvatarAsset> = {')
    lines += entries
    lines.append('};')
    open(os.path.join(MODELS, 'avatars.ts'), 'w').write('\n'.join(lines) + '\n')
    print('index:', len(entries), 'avatars')


if __name__ == '__main__':
    main(sys.argv[1], set(sys.argv[2:]))
