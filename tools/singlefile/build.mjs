// Builds dist-single/index.html: the whole game + a few embedded assets in ONE html file (quick test).
// Usage: node tools/singlefile/build.mjs [--variants soldier_m_acu,survivor_m_hoodie_blue]
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, statSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const pub = (p) => resolve(root, 'public', p);
const argv = process.argv.slice(2);
const vi = argv.indexOf('--variants');
const variants = (vi >= 0 ? argv[vi + 1] : 'soldier_m_acu,survivor_m_hoodie_blue').split(',');

const embed = {};
const add = (path, buf) => (embed[path] = Buffer.from(buf).toString('base64'));

// Character manifest trimmed to the chosen variants (no LOD1 files: only the player is on screen).
const cm = JSON.parse(readFileSync(pub('assets/characters/manifest.json'), 'utf8'));
cm.variants = variants.map((id) => cm.variants.find((v) => v.id === id)).filter(Boolean);
for (const v of cm.variants) for (const k of Object.keys(v)) if (/lod/i.test(k)) delete v[k];
delete cm.lod;
add('assets/characters/manifest.json', JSON.stringify(cm));
for (const v of cm.variants) add(`assets/characters/${v.file.split('/').pop()}`, readFileSync(pub(`assets/characters/${v.file.split('/').pop()}`)));

// All animation clips.
const am = readFileSync(pub('assets/anims/manifest.json'));
add('assets/anims/manifest.json', am);
for (const f of ['locomotion.glb', 'rifle.glb', 'pistol.glb', 'actions.glb']) add(`assets/anims/${f}`, readFileSync(pub(`assets/anims/${f}`)));

mkdirSync(resolve(here, '.gen'), { recursive: true });
writeFileSync(resolve(here, '.gen/embedded.ts'), `// generated by build.mjs\nexport const EMBED: Record<string, string> = ${JSON.stringify(embed)};\n`);
console.log('embedded:', Object.keys(embed).join(', '));

execSync(`npx vite build --config ${resolve(here, 'vite.config.ts')}`, { cwd: root, stdio: 'inherit' });
const out = resolve(root, 'dist-single/index.html');
copyFileSync(out, resolve(root, 'battlegrounds-quicktest.html'));
console.log(`OK -> battlegrounds-quicktest.html (${(statSync(out).size / 1e6).toFixed(1)} MB)`);
