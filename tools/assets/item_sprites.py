def _rgba(hex_code: str) -> tuple[int, int, int, int]:
    h = hex_code.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255


def legend(extra: dict[str, str] | None = None, **groups: str) -> dict[str, tuple[int, int, int, int]]:
    """legend(IRON="012345", BONE="abcde") maps each char to that palette tone (dark->light).

    A space in the char string skips a tone.  ``extra`` maps single chars to hex codes.
    """
    out: dict[str, tuple[int, int, int, int]] = {}
    for pal_name, chars in groups.items():
        tones = PALETTES[pal_name]
        if len(chars) > len(tones):
            raise ValueError(f"{pal_name} has only {len(tones)} tones, got {chars!r}")
        for ch, tone in zip(chars, tones):
            if ch == " ":
                continue
            if ch in out:
                raise ValueError(f"legend char {ch!r} assigned twice")
            out[ch] = _rgba(tone)
    for ch, tone in (extra or {}).items():
        if ch in out:
            raise ValueError(f"legend char {ch!r} assigned twice")
        out[ch] = _rgba(tone)
    return out


@dataclass
class Sprite:
    name: str
    model: str                      # handheld | generated | bow | crossbow
    legend: dict
    base: str
    overlays: list[str] = field(default_factory=list)
    frametime: int | None = None
    item_def: str | None = "simple"  # simple | bow | crossbow | None (state textures)


SPRITES: list[Sprite] = []


def sprite(name, model, lg, base, overlays=(), frametime=None, item_def="simple"):
    SPRITES.append(Sprite(name, model, lg, base, list(overlays), frametime, item_def))


