# ==========================================================================
# Build machinery
# ==========================================================================
def parse_grid(text: str, name: str, what: str) -> list[str]:
    rows = [r.strip() for r in text.strip("\n").split("\n")]
    if len(rows) != 16:
        raise ValueError(f"{name}: {what} has {len(rows)} rows, expected 16")
    for i, r in enumerate(rows):
        if len(r) != 16:
            raise ValueError(f"{name}: {what} row {i} has {len(r)} chars: {r!r}")
    return rows


def frames_of(sp: Sprite) -> list[list[str]]:
    base = parse_grid(sp.base, sp.name, "base")
    if not sp.overlays:
        return [base]
    frames = []
    for k, ov in enumerate(sp.overlays):
        ovr = parse_grid(ov, sp.name, f"overlay {k}")
        frames.append(["".join(b if o == "," else o for b, o in zip(br, orow)) for br, orow in zip(base, ovr)])
    return frames


def render(sp: Sprite) -> np.ndarray:
    frames = frames_of(sp)
    img = np.zeros((16 * len(frames), 16, 4), dtype=np.uint8)
    for f, rows in enumerate(frames):
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == ".":
                    continue
                if ch not in sp.legend:
                    raise ValueError(f"{sp.name}: frame {f} ({x},{y}) unknown char {ch!r}")
                img[f * 16 + y, x] = sp.legend[ch]
    return img


def lint(sp: Sprite, img: np.ndarray) -> list[str]:
    """Style checks: no pure black, no isolated single pixels."""
    issues = []
    opaque = img[..., 3] > 0
    if np.any(opaque & (img[..., :3].sum(axis=-1) == 0)):
        issues.append("uses pure black")
    for f in range(img.shape[0] // 16):
        a = opaque[f * 16:(f + 1) * 16]
        pad = np.pad(a, 1)
        neigh = sum(np.roll(np.roll(pad, dy, 0), dx, 1) for dy in (-1, 0, 1) for dx in (-1, 0, 1)
                    if (dy, dx) != (0, 0))[1:-1, 1:-1]
        lonely = np.argwhere(a & (neigh == 0))
        for y, x in lonely:
            issues.append(f"frame {f}: isolated pixel at ({x},{y})")
    return issues


def model_json(sp: Sprite) -> dict:
    parent = {
        "handheld": "minecraft:item/handheld",
        "generated": "minecraft:item/generated",
        "bow": "minecraft:item/bow",
        "crossbow": "minecraft:item/crossbow",
    }[sp.model]
    return {"parent": parent, "textures": {"layer0": f"{MOD_ID}:item/{sp.name}"}}


def _m(name: str) -> dict:
    return {"type": "minecraft:model", "model": f"{MOD_ID}:item/{name}"}


def item_def_json(sp: Sprite) -> dict:
    n = sp.name
    if sp.item_def == "simple":
        return {"model": _m(n)}
    if sp.item_def == "bow":
        return {"model": {
            "type": "minecraft:condition", "property": "minecraft:using_item",
            "on_false": _m(n),
            "on_true": {
                "type": "minecraft:range_dispatch", "property": "minecraft:use_duration", "scale": 0.05,
                "entries": [{"threshold": 0.65, "model": _m(f"{n}_pulling_1")},
                            {"threshold": 0.9, "model": _m(f"{n}_pulling_2")}],
                "fallback": _m(f"{n}_pulling_0")}}}
    if sp.item_def == "crossbow":
        return {"model": {
            "type": "minecraft:select", "property": "minecraft:charge_type",
            "cases": [{"when": "arrow", "model": _m(f"{n}_arrow")},
                      {"when": "rocket", "model": _m(f"{n}_firework")}],
            "fallback": {
                "type": "minecraft:condition", "property": "minecraft:using_item",
                "on_false": _m(n),
                "on_true": {
                    "type": "minecraft:range_dispatch", "property": "minecraft:crossbow/pull",
                    "entries": [{"threshold": 0.58, "model": _m(f"{n}_pulling_1")},
                                {"threshold": 1.0, "model": _m(f"{n}_pulling_2")}],
                    "fallback": _m(f"{n}_pulling_0")}}}}
    raise ValueError(sp.item_def)


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n")


def contact_sheet(images: list[tuple[str, np.ndarray]], out: Path, scale: int = 8, cols: int = 8) -> None:
    from PIL import ImageDraw, ImageFont
    tiles = []
    for name, img in images:
        n = img.shape[0] // 16
        for f in range(n):
            tiles.append((name if n == 1 else f"{name}[{f}]", img[f * 16:(f + 1) * 16]))
    cw, ch = 16 * scale + 24, 16 * scale + 30
    rows = (len(tiles) + cols - 1) // cols
    sheet = Image.new("RGBA", (cols * cw, rows * ch), (112, 112, 112, 255))
    draw = ImageDraw.Draw(sheet)
    try:
        font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 11)
    except OSError:
        font = ImageFont.load_default()
    for i, (name, t) in enumerate(tiles):
        x, y = (i % cols) * cw + 12, (i // cols) * ch + 6
        big = Image.fromarray(t, "RGBA").resize((16 * scale, 16 * scale), Image.NEAREST)
        sheet.alpha_composite(big, (x, y))
        draw.text((x, y + 16 * scale + 3), name[:22], fill=(255, 255, 255, 255), font=font)
    out.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(out)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="lint only, write nothing")
    ap.add_argument("--sheet", type=Path, help="also write a contact sheet PNG here")
    ap.add_argument("--only", help="comma separated sprite names")
    args = ap.parse_args(argv)

    only = set(args.only.split(",")) if args.only else None
    names = [s.name for s in SPRITES]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        print(f"duplicate sprite names: {sorted(dupes)}", file=sys.stderr)
        return 1

    rendered = []
    problems = 0
    for sp in SPRITES:
        if only and sp.name not in only:
            continue
        img = render(sp)
        for issue in lint(sp, img):
            print(f"[lint] {sp.name}: {issue}")
            problems += "pure black" in issue
        rendered.append((sp.name, img))
        if args.check:
            continue
        TEX_DIR.mkdir(parents=True, exist_ok=True)
        Image.fromarray(img, "RGBA").save(TEX_DIR / f"{sp.name}.png")
        mcmeta = TEX_DIR / f"{sp.name}.png.mcmeta"
        if sp.overlays:
            write_json(mcmeta, {"animation": {"frametime": sp.frametime, "interpolate": False}})
        elif mcmeta.exists():
            mcmeta.unlink()
        write_json(MODEL_DIR / f"{sp.name}.json", model_json(sp))
        if sp.item_def:
            write_json(ITEMDEF_DIR / f"{sp.name}.json", item_def_json(sp))

    if args.sheet:
        contact_sheet(rendered, args.sheet)
    print(f"{len(rendered)} sprites {'checked' if args.check else 'written'}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
