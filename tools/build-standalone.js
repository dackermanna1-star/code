#!/usr/bin/env node
// Builds dist/ROBLOX2008.html: one self-contained file with the game client,
// every place, a game menu and an avatar maker. Needs esbuild
// (npm i -D esbuild, or set ESBUILD_PATH).
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const esbuild = require(process.env.ESBUILD_PATH || 'esbuild');

const b64 = (f) => fs.readFileSync(path.join(root, f)).toString('base64');
const fontUrl = (f) => `url(data:font/woff2;base64,${b64('public/fonts/' + f)})`;
const fonts = (css) => css.replace(/url\(\/fonts\/([^)]+)\)/g, (_, f) => fontUrl(f));
const fontFace = `@font-face{font-family:'Comic Sans MS';src:local('Comic Sans MS'),${fontUrl('ComicNeue-Regular.woff2')} format('woff2');font-weight:normal;}
@font-face{font-family:'Comic Sans MS';src:local('Comic Sans MS Bold'),${fontUrl('ComicNeue-Bold.woff2')} format('woff2');font-weight:bold;}
@font-face{font-family:'Comic Neue';src:${fontUrl('ComicNeue-Regular.woff2')} format('woff2');}\n`;

const gen = path.join(root, 'standalone', 'generated');
fs.mkdirSync(gen, { recursive: true });
fs.writeFileSync(path.join(gen, 'assets.js'), `// generated by tools/build-standalone.js
export const MENU_CSS = ${JSON.stringify(fontFace + fs.readFileSync(path.join(root, 'standalone/menu.css'), 'utf8'))};
export const CLIENT_CSS = ${JSON.stringify(fonts(fs.readFileSync(path.join(root, 'public/css/client.css'), 'utf8')))};
export const LOGO = 'data:image/png;base64,${b64('public/images/roblox_logo.png')}';
`);

const result = esbuild.buildSync({
  entryPoints: [path.join(root, 'standalone/main.js')],
  bundle: true, format: 'iife', minify: true, write: false, target: 'es2020', legalComments: 'none',
  alias: { three: path.join(root, 'public/js/vendor/three.module.min.js') },
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const licences = ['public/js/vendor/LICENSE.three.txt', 'public/js/vendor/LICENSE.cannon-es.txt']
  .map((f) => fs.existsSync(path.join(root, f)) ? fs.readFileSync(path.join(root, f), 'utf8') : '').join('\n');
const html = `<!DOCTYPE html>
<html><head><meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>ROBLOX (2008 recreation)</title>
<!-- Unofficial, non-commercial recreation of ROBLOX circa 2008. Not affiliated with Roblox Corporation.
     Contains no original ROBLOX images or sounds. Includes three.js and cannon-es (MIT) and Comic Neue (SIL OFL).
${licences.replace(/--/g, '- -')}
-->
</head><body>
<script>${js}</script>
</body></html>`;
const out = path.join(root, 'dist', 'ROBLOX2008.html');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html);
console.log(`wrote ${path.relative(root, out)} (${(html.length / 1024 / 1024).toFixed(2)} MB)`);
