#!/usr/bin/env node
/* Build: compile story/main.ink -> js/story.js, vendor the ink runtime,
 * list art scripts in index.html, and emit dist/artifact.html (the page
 * body without document skeleton, for publishing as an artifact). */
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ink = require(path.join(root, 'node_modules/inkjs/dist/ink-full.js'));

// 1. compile ink (INCLUDE resolved relative to story/)
const storyDir = path.join(root, 'story');
const fileHandler = {
  ResolveInkFilename: (name) => path.join(storyDir, name),
  LoadInkFileContents: (p) => fs.readFileSync(p, 'utf8')
};
const errors = [], warnings = [];
const opts = new ink.CompilerOptions(path.join(storyDir, 'main.ink'), [], false, (msg, type) => {
  (type === 2 || /ERROR/.test(msg) ? errors : warnings).push(msg);
}, fileHandler);
const src = fs.readFileSync(path.join(storyDir, 'main.ink'), 'utf8');
let story = null;
try { story = new ink.Compiler(src, opts).Compile(); } catch (e) { errors.push(String(e && e.message || e)); }
if (warnings.length) console.log(`warnings (${warnings.length}):\n  ` + warnings.slice(0, 40).join('\n  '));
if (errors.length || !story) { console.error(`ERRORS (${errors.length}):\n  ` + errors.join('\n  ')); process.exit(1); }
const json = story.ToJson();
fs.writeFileSync(path.join(root, 'js/story.js'), '/* generated by tools/build.mjs from story/*.ink — do not edit */\nwindow.STORY_JSON = ' + json + ';\n');
console.log(`story: ${(json.length / 1024).toFixed(0)} KB`);

// 2. vendor runtime
fs.mkdirSync(path.join(root, 'js/vendor'), { recursive: true });
fs.copyFileSync(path.join(root, 'node_modules/inkjs/dist/ink.js'), path.join(root, 'js/vendor/ink.js'));

// 3. art scripts into index.html
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const pxDir = path.join(root, 'js/px');
const pxFiles = fs.existsSync(pxDir) ? ['px.js', 'pxchar.js', ...fs.readdirSync(pxDir).filter((f) => f.endsWith('.js') && f !== 'px.js' && f !== 'pxchar.js').sort()].filter((f) => fs.existsSync(path.join(pxDir, f))) : [];
const tags = pxFiles.map((f) => `<script src="js/px/${f}"></script>`).join('\n');
html = html.replace(/<!--ART-FILES-->[\s\S]*?(<!--\/ART-FILES-->|(?=\n<script src="js\/audio.js"))/, `<!--ART-FILES-->\n${tags}\n<!--/ART-FILES-->`);
fs.writeFileSync(path.join(root, 'index.html'), html);

// 4. artifact page: everything between the markers, minus </head><body>
const start = html.indexOf('<!--ARTIFACT-START-->'), end = html.indexOf('<!--ARTIFACT-END-->');
let page = html.slice(start + '<!--ARTIFACT-START-->'.length, end);
page = page.replace(/<!--HEAD-END-->\s*<\/head>\s*<body>/, '');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/artifact.html'), page.trim() + '\n');
console.log(`art files: ${pxFiles.length}; wrote js/story.js, js/vendor/ink.js, dist/artifact.html`);
