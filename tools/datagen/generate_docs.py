#!/usr/bin/env python3
"""Generates docs/WEAPONS.md and docs/ATTACHMENTS.md from the shipped data and language files.

The reference tables are derived from src/main/resources (the same JSON the mod loads), so they cannot drift
from the actual values. Re-run after changing tools/datagen/generate_data.py:

    python3 tools/datagen/generate_data.py && python3 tools/datagen/generate_docs.py
"""
import json
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "src", "main", "resources")
DATA = os.path.join(RES, "data", "calibercraft")
DEFS = os.path.join(DATA, "calibercraft")
LANG = json.load(open(os.path.join(RES, "assets", "calibercraft", "lang", "en_us.json"), encoding="utf-8"))
DOCS = os.path.join(ROOT, "docs")

WEAPON_ORDER = ["m9", "revolver", "vector9", "mp5", "ar15", "ak", "bullpup", "pump_shotgun", "auto_shotgun", "sniper", "dmr", "lmg"]
SLOT_ORDER = ["optic", "muzzle", "barrel", "grip", "stock", "magazine", "tactical", "charm"]


def load_dir(name):
    d = os.path.join(DEFS, name)
    return {f[:-5]: json.load(open(os.path.join(d, f), encoding="utf-8")) for f in sorted(os.listdir(d)) if f.endswith(".json")}


WEAPONS = load_dir("weapon")
ATTACHMENTS = load_dir("attachment")
AMMO = load_dir("ammo")
SKINS = load_dir("skin")
RECIPES = {f[:-5]: json.load(open(os.path.join(DATA, "recipe", f), encoding="utf-8"))
           for f in sorted(os.listdir(os.path.join(DATA, "recipe"))) if f.endswith(".json")}
LOOT = {}
for tier in ("common", "military", "rare"):
    table = json.load(open(os.path.join(DATA, "loot_table", "inject", tier + ".json"), encoding="utf-8"))
    for pool in table["pools"]:
        for e in pool["entries"]:
            if "name" in e:
                LOOT.setdefault(e["name"].split(":", 1)[1], []).append(tier)


def path(ident):
    return ident.split(":", 1)[1]


def name(key, fallback):
    return LANG.get(key, fallback)


def item_name(item_id):
    if item_id.startswith("#"):
        return "any " + path(item_id[1:]).replace("_", " ").title()
    p = path(item_id) if ":" in item_id else item_id
    if item_id.startswith("minecraft:"):
        return p.replace("_", " ").title()
    return name("item.calibercraft." + p, name("block.calibercraft." + p, p))


def stat_name(stat):
    return name("calibercraft.stat_name." + stat, stat.replace("_", " "))


def fmt(v):
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)


def seconds(ticks):
    return f"{ticks / 20:.2f}s"


def modifier_text(m):
    v = m["value"]
    if m["stat"] == "pellets" and m["op"] == "multiply" and v == 0:
        return "single projectile"
    if m["op"] == "multiply":
        pct = (v - 1) * 100
        return f"{stat_name(m['stat'])} {pct:+.0f}%"
    return f"{stat_name(m['stat'])} {v:+g}"


def recipe_text(item):
    r = RECIPES.get(item)
    if r is None:
        return "—"
    if r["type"] == "minecraft:crafting_shaped":
        counts = {}
        for row in r["pattern"]:
            for ch in row:
                if ch != " ":
                    counts[ch] = counts.get(ch, 0) + 1
        parts = [f"{n}× {item_name(r['key'][ch])}" for ch, n in counts.items()]
        return "shaped: " + ", ".join(parts)
    if r["type"] == "minecraft:crafting_shapeless":
        counts = {}
        for ing in r["ingredients"]:
            counts[ing] = counts.get(ing, 0) + 1
        out = r["result"].get("count", 1)
        return ("shapeless: " + ", ".join(f"{n}× {item_name(i)}" for i, n in counts.items())
                + (f" → {out}" if out > 1 else ""))
    return r["type"]


def acquisition(item):
    parts = []
    if item in RECIPES:
        parts.append("crafting")
    if item in LOOT:
        parts.append("loot (" + ", ".join(sorted(set(LOOT[item]))) + ")")
    return "; ".join(parts) or "creative only"


def reload_text(w):
    r = w["reload"]
    if r["type"] == "single":
        s = r["single"]
        return (f"single rounds: start {seconds(s['start']['length'])}, {seconds(s['per_round'])}/round, "
                f"end {seconds(s['end']['length'])} ({seconds(s['end_empty']['length'])} when empty)")
    t = r.get("tactical", {}).get("length", 0)
    e = r.get("empty", {}).get("length", 0)
    if r["type"] == "cylinder" or not e:
        return f"{r['type']}: {seconds(t)}"
    return f"magazine: {seconds(t)} tactical / {seconds(e)} empty"


def weapons_md():
    out = ["# Weapon reference", "",
           "Generated by `tools/datagen/generate_docs.py` from the shipped data "
           "(`data/calibercraft/calibercraft/weapon/*.json`). Every value can be changed by a datapack or by "
           "`weaponOverrides` in `config/calibercraft/server.json` (see [CONFIG.md](CONFIG.md)).", "",
           "Units: damage in half-hearts (2 = one heart), ranges in blocks, velocity in blocks/tick, spread in "
           "degrees, times in ticks (20 ticks = 1 second).", "",
           "## Overview", "",
           "| Weapon | Category | Caliber | Modes | Action | Damage | RPM | Mag | Eff. range | Velocity | Reload |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for wid in WEAPON_ORDER:
        w = WEAPONS[wid]
        st = w["stats"]
        dmg = fmt(st["damage"]) + (f" ×{st['pellets']} pellets" if st.get("pellets", 1) > 1 else "")
        out.append(f"| {item_name(wid)} | {name('calibercraft.category.' + w['category'], w['category'])} | "
                   f"{name('calibercraft.caliber.' + path(w['caliber']), path(w['caliber']))} | "
                   f"{', '.join(w['fire_modes'])}{' (' + str(w['burst_count']) + ')' if 'burst' in w['fire_modes'] else ''} | "
                   f"{w['action'].replace('_', ' ')} | {dmg} | {fmt(st['rpm'])} | {fmt(st['magazine'])} | "
                   f"{fmt(st['effective_range'])} | {fmt(st['velocity'])} | {reload_text(w)} |")
    out += ["", "Acquisition: every weapon can be crafted (recipes need *Gun Parts* and usually *Precision Parts*) "
            "and appears in the creative tab. Loot tiers: **common** = dungeons, mineshafts, shipwreck supply, "
            "buried treasure; **military** = weaponsmith, pillager outpost, stronghold corridor, desert pyramid, "
            "jungle temple; **rare** = ancient city, woodland mansion, bastion, trial chamber rewards.", ""]
    for wid in WEAPON_ORDER:
        w = WEAPONS[wid]
        st = w["stats"]
        out += [f"## {item_name(wid)} (`calibercraft:{wid}`)", ""]
        out.append(f"- **Acquisition:** {acquisition(wid)}; recipe {recipe_text(wid)}")
        out.append(f"- **Reload:** {reload_text(w)}")
        if w.get("cycle", {}).get("length"):
            if w["action"] in ("bolt", "pump"):
                out.append(f"- **Manual {w['action']} cycle after each shot:** {seconds(w['cycle']['length'])}")
            else:
                out.append(f"- **Chambering by hand** (only when loaded without a chambered round): {seconds(w['cycle']['length'])}")
        ammo = sorted((a for a in AMMO.values() if a["caliber"] == w["caliber"]), key=lambda a: a.get("order", 0))
        out.append("- **Ammunition:** " + ", ".join(item_name(a["item"]) for a in ammo))
        defaults = w.get("default_attachments", {})
        if defaults:
            out.append("- **Factory attachments:** " + ", ".join(
                f"{name('calibercraft.slot.' + s, s)}: {item_name(a)}" for s, a in defaults.items()))
        out += ["", "| Stat | Value |", "|---|---|"]
        for k, v in st.items():
            label = stat_name(k)
            out.append(f"| {label[:1].upper() + label[1:]} | {fmt(v)} |")
        out += ["", "| Slot | Compatible attachments |", "|---|---|"]
        for slot in SLOT_ORDER:
            allowed = w.get("attachments", {}).get(slot, [])
            out.append(f"| {name('calibercraft.slot.' + slot, slot)} | "
                       f"{', '.join(item_name(a) for a in allowed) if allowed else '—'} |")
        out.append("")
    return "\n".join(out)


def attachments_md():
    out = ["# Attachment, ammunition and skin reference", "",
           "Generated by `tools/datagen/generate_docs.py` from the shipped data. Modifiers are applied as "
           "`(base + Σadd) × Πmultiply`, then clamped to each stat's limits; the gunsmith screen shows the exact "
           "before/after values for the weapon being modified.", "",
           "**Field changes:** optics, muzzle devices, grips, magazines, tactical devices and charms can be swapped "
           "anywhere (default `fieldCustomization: \"quick_detach\"`); barrels and stocks need a Gunsmith Bench "
           "within 8 blocks.", ""]
    for slot in SLOT_ORDER:
        rows = [(aid, a) for aid, a in ATTACHMENTS.items() if a["slot"] == slot]
        if not rows:
            continue
        out += [f"## {name('calibercraft.slot.' + slot, slot)}", "",
                "| Attachment | Effects | Flags | Fits | Recipe |", "|---|---|---|---|---|"]
        for aid, a in rows:
            fits = [item_name(w) for w in WEAPON_ORDER if f"calibercraft:{aid}" in WEAPONS[w].get("attachments", {}).get(slot, [])]
            effects = ", ".join(modifier_text(m) for m in a.get("modifiers", [])) or "cosmetic"
            flags = ", ".join(a.get("flags", [])) or "—"
            if a.get("optic"):
                flags = (flags + ", " if flags != "—" else "") + "reticle: " + a["optic"].get("reticle", "?")
            out.append(f"| {item_name(a['item'])} | {effects} | {flags} | {', '.join(fits) or '—'} | {recipe_text(path(a['item']))} |")
        out.append("")
    out += ["## Ammunition", "", "Ammunition is a separate attachment-like choice: press **N** to select the type "
            "loaded on the next reload.", "",
            "| Ammunition | Caliber | Effects | Sets on fire | Recipe |", "|---|---|---|---|---|"]
    for aid, a in sorted(AMMO.items(), key=lambda kv: (kv[1]["caliber"], kv[1].get("order", 0))):
        effects = ", ".join(modifier_text(m) for m in a.get("modifiers", [])) or "standard"
        fire = f"{a['fire_seconds']}s" if a.get("fire_seconds") else "—"
        out.append(f"| {item_name(a['item'])} | {name('calibercraft.caliber.' + path(a['caliber']), path(a['caliber']))} | "
                   f"{effects} | {fire} | {recipe_text(path(a['item']))} |")
    out += ["", "## Skins", "",
            f"Every weapon accepts every skin ({len(SKINS)} finishes × {len(WEAPONS)} weapons = "
            f"{len(SKINS) * len(WEAPONS)} variants, plus the standard finish). Skins are cosmetic only. Finishes marked "
            "*kit* consume a Prismatic Finish Kit when applied in survival (configurable with `rareSkinsRequireKit`); "
            "animated finishes glow and pulse.", "",
            "| Skin | Rarity | Needs kit |", "|---|---|---|"]
    for sid, s in sorted(SKINS.items(), key=lambda kv: kv[1].get("order", 0)):
        out.append(f"| {name('calibercraft.skin.' + sid, sid)} | {name('calibercraft.rarity.' + s['rarity'], s['rarity'])} | "
                   f"{'yes' if s.get('requires_kit') else 'no'} |")
    out.append("")
    return "\n".join(out)


def main():
    os.makedirs(DOCS, exist_ok=True)
    for fname, text in (("WEAPONS.md", weapons_md()), ("ATTACHMENTS.md", attachments_md())):
        with open(os.path.join(DOCS, fname), "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote docs/" + fname)


if __name__ == "__main__":
    main()
