def small_digits(text: str) -> np.ndarray:
	cols = []
	for i, ch in enumerate(text):
		g = np.array([[c == "#" for c in r] for r in DIGITS_3x5[ch]], dtype=bool)
		if i:
			cols.append(np.zeros((5, 1), dtype=bool))
		cols.append(g)
	return np.concatenate(cols, axis=1)
