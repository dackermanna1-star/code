ROWS = 9


def _norm(rows: list[str]) -> np.ndarray:
	w = max(len(r) for r in rows)
	rows = rows + ["." * w] * (ROWS - len(rows))
	return np.array([[c == "#" for c in r.ljust(w, ".")] for r in rows], dtype=bool)


FONT = {k: _norm(v) for k, v in _RAW.items()}
GOTHIC = {k: _norm(v) for k, v in _GOTHIC.items()}


def glyph(ch: str, font=None) -> np.ndarray:
	font = font or FONT
	if ch in font:
		return font[ch]
	if ch.upper() in font:
		return font[ch.upper()]
	return FONT["?"]


def layout(text: str, spacing: int = 1, font=None) -> list[tuple[str, int, np.ndarray]]:
	"""Return [(char, x, mask)] in font units."""
	out = []
	x = 0
	for ch in text:
		g = glyph(ch, font)
		out.append((ch, x, g))
		x += g.shape[1] + spacing
	return out


def text_width(text: str, spacing: int = 1, font=None) -> int:
	lay = layout(text, spacing, font)
	if not lay:
		return 0
	ch, x, g = lay[-1]
	return x + g.shape[1]


def text_mask(text: str, spacing: int = 1, font=None, rows: int = ROWS) -> np.ndarray:
	w = text_width(text, spacing, font)
	m = np.zeros((rows, w), dtype=bool)
	for ch, x, g in layout(text, spacing, font):
		m[:g.shape[0], x:x + g.shape[1]] |= g[:rows]
	return m


def scale_mask(m: np.ndarray, s: int) -> np.ndarray:
	return np.kron(m, np.ones((s, s), dtype=bool)).astype(bool)


def dilate(m: np.ndarray, r: int = 1, diag: bool = True) -> np.ndarray:
	out = m.copy()
	h, w = m.shape
	for dy in range(-r, r + 1):
		for dx in range(-r, r + 1):
			if not diag and abs(dx) + abs(dy) > r:
				continue
			sh = np.zeros_like(m)
			ys = slice(max(0, dy), h + min(0, dy))
			yd = slice(max(0, -dy), h + min(0, -dy))
			xs = slice(max(0, dx), w + min(0, dx))
			xd = slice(max(0, -dx), w + min(0, -dx))
			sh[ys, xs] = m[yd, xd]
			out |= sh
	return out


def shift(m: np.ndarray, dx: int, dy: int) -> np.ndarray:
	h, w = m.shape
	out = np.zeros_like(m)
	ys = slice(max(0, dy), h + min(0, dy))
	yd = slice(max(0, -dy), h + min(0, -dy))
	xs = slice(max(0, dx), w + min(0, dx))
	xd = slice(max(0, -dx), w + min(0, -dx))
	out[ys, xs] = m[yd, xd]
	return out


