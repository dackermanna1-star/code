// Dev tool: measure building/wall heights of an original de_dust2.bsp (from your
// own install) on the area grid, so the recreated walls have the same skyline.
//
//   node tools/measure-massing.mjs <path/to/de_dust2.bsp> > src/map/dust2_massing.js
//
// For every 8-unit cell it records the top of the highest solid that has open air
// (or the sky brush) above it: roofs, wall tops, or the height where a wall meets
// the sky. Heights are stored /8 in one byte per cell (0 = no data), base64.
import { readFileSync } from 'fs';
import { parseBsp, BspHulls, CONTENTS_SOLID } from '../src/bsp/bsp30.js';

const CONTENTS_SKY = -6;
const [bspPath] = process.argv.slice(2);
const buf = readFileSync(bspPath);
const bsp = parseBsp(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const hulls = new BspHulls(bsp);
const head0 = bsp.models[0].headnode[0];
const C = (x, y, z) => hulls.pointContents(0, head0, [x, y, z]);

const X0 = -2432, Y0 = -1312, X1 = 2016, Y1 = 3296, G = 8;
const W = (X1 - X0) / G, H = (Y1 - Y0) / G;
const out = new Uint8Array(W * H);
for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) {
  const x = X0 + (i + 0.5) * G, y = Y0 + (j + 0.5) * G;
  // walk down from above the sky to the first solid below air or sky
  let z = 900, seenOpen = false, top = null;
  for (; z > -640; z -= 8) {
    const c = C(x, y, z);
    if (c === CONTENTS_SOLID) { if (seenOpen) { top = z; break; } } else seenOpen = true;
  }
  if (top == null) continue;
  // refine to 1 unit
  let lo = top, hi = top + 8;
  for (let k = 0; k < 6; k++) { const m = (lo + hi) / 2; if (C(x, y, m) === CONTENTS_SOLID) lo = m; else hi = m; }
  const h = Math.round(lo / 8);
  out[j * W + i] = Math.max(1, Math.min(255, h + 81)); // -640..1392 -> 1..255
}
// run-length encode as (value, count<=255) byte pairs
const rle = [];
for (let k = 0; k < out.length;) {
  let n = 1; while (k + n < out.length && out[k + n] === out[k] && n < 255) n++;
  rle.push(out[k], n); k += n;
}
const b64 = Buffer.from(rle).toString('base64');
const lines = b64.match(/.{1,100}/g).map((l) => `  '${l}'`).join(',\n');
console.log(`// Generated by tools/measure-massing.mjs: building/wall top heights of de_dust2 on
// an ${G}-unit grid (height/8 + 81 per cell, 0 = none), run-length encoded as
// (value, count) byte pairs, base64. Used by AreaMap for the original skyline.
export const MASSING = {
  x0: ${X0}, y0: ${Y0}, cell: ${G}, w: ${W}, h: ${H},
  rle: [
${lines},
  ].join(''),
};`);
