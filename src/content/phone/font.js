// Cyrillic letters that share a Latin shape
const ALIAS = {
  А: 'A', В: 'B', Е: 'E', К: 'K', М: 'M', Н: 'H', О: 'O', Р: 'P', С: 'C', Т: 'T', Х: 'X',
  а: 'a', е: 'e', о: 'o', р: 'p', с: 'c', у: 'y', х: 'x',
  '…': '.', '’': "'", '‘': "'", '“': '"', '”': '"', '−': '-', ' ': ' ',
}

export const CELL_H = 10
export const SPACE_W = 3

/** Parsed glyph: { w, rows: [[x, y], ...] } (pixel list). */
const cache = new Map()
function parse(def) {
  const [top, body] = def.split(':')
  const rows = body.split('/')
  const w = Math.max(...rows.map(r => r.length))
  const px = []
  rows.forEach((r, j) => {
    for (let i = 0; i < r.length; i++) if (r[i] === '#') px.push(i, +top + j)
  })
  return { w, px }
}

export function glyph(ch) {
  let g = cache.get(ch)
  if (g) return g
  let def = G[ch]
  if (!def && ALIAS[ch]) def = G[ALIAS[ch]] ?? null
  if (!def && ch === ' ') { g = { w: SPACE_W, px: [] }; cache.set(ch, g); return g }
  if (!def) {
    // unknown: try the other case, else a small box
    const alt = ch.toUpperCase() !== ch ? ch.toUpperCase() : ch.toLowerCase()
    def = G[alt] ?? (ALIAS[alt] ? G[ALIAS[alt]] : null) ?? '3:###/#.#/#.#/#.#/###'
  }
  g = parse(def)
  cache.set(ch, g)
  return g
}

