// ASCII pixel-art templates for item icons (16×16). See icons.js for the palette letters:
//   a b c d primary ramp   e f g h secondary   i j k l tertiary   m n o p metal   u v w x wood   q r s t dark
//   W white L light-grey P paper Y gold R red G green B blue K black F orange S skin T cardboard V/X brass
//   Q/U/N glass O outline M blood H sparkle Z grey y pale-flame z dark-brown 1-9 template-local (pal)
// '.' = transparent. A 1px dark outline is added automatically around the shape.
// Templates: { rows: [16 strings], colors?: default ramp colours, pal?: {digit: '#hex'}, outline?: false }

export const TEMPLATES = {};
export const DECALS = {};

function T(name, rows, opts = {}) {
  if (rows.length !== 16) throw new Error(`icon template ${name}: ${rows.length} rows`);
  rows.forEach((r, i) => { if (r.length !== 16) throw new Error(`icon template ${name} row ${i}: length ${r.length}`); });
  TEMPLATES[name] = { rows, ...opts };
}
function D(name, rows, opts = {}) {
  while (rows.length < 16) rows.push('................');
  rows.forEach((r, i) => { if (r.length !== 16) throw new Error(`decal ${name} row ${i}: length ${r.length}`); });
  DECALS[name] = { rows, ...opts };
}

