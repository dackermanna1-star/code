// =============================================================================
// CITY & SETTLEMENTS MODULE — everything man-made outside the airport fences.
//
//   departure region 'Cedar Bay'  (anchored at app.world.departureOrigin):
//       farmsteads, small town with main street / church / water tower / grain
//       elevator, highway + rail with moving traffic, power lines, wind farm,
//       lake-side cabins.                                     -> departure.js
//   arrival region 'Port Solano'  (anchored at app.world.arrivalOrigin):
//       coastal city with downtown towers, suburbs, port, marina, pier,
//       stadium, highways with interchanges, night lights.      -> arrival.js
//
// Each region is a Group in app.worldRoot positioned at its anchor; all content
// is built in anchor-local coordinates from the geography contract (geo.js).
// Regions are generated by generator functions that can run synchronously or
// incrementally (a few ms per frame) — the arrival region is (re)built lazily
// when the aircraft gets within range or after 'world:arrivalMoved'.
//
// Draw calls: departure ~11, arrival ~10 (merged statics, custom-instanced
// houses / trees, GPU-animated traffic, additive light points).
//
// API: { departure: {group}, arrival: {group}, nightFactor, lightsFactor,
//        setNightFactor(v|null), rebuild(), stats, ready }
// =============================================================================
import * as THREE from 'three';
import { CITY_U, createBuildingMaterial, createTreeMaterial, createRoadMaterial, createPointMaterial } from './materials.js';
import { unitHouse, unitBroadleaf, unitConifer, unitPalm } from './shapes.js';
import { Land, sstep, clamp } from './util.js';
import { SHADOW_U, createMergedShadowMaterial, createHouseShadowMaterial, createTreeShadowMaterial } from './shadows.js';
import { buildArrival } from './arrival.js';
import { buildDeparture } from './departure.js';
import { EnRoute } from './enroute.js';

const DEG = Math.PI / 180;

class City {
  constructor(app) {
    this.app = app;
    this.detail = clamp(app.quality?.detail ?? 1, 0, 3);
    this.mats = {
      bld: createBuildingMaterial(),
      inst: createBuildingMaterial({ instanced: true, name: 'city.instBuildings' }),
      tree: createTreeMaterial(),
      road: createRoadMaterial(),
      points: createPointMaterial(),
      shadow: { merged: createMergedShadowMaterial(), houses: createHouseShadowMaterial(), trees: createTreeShadowMaterial() },
    };
    this.unit = { gable: unitHouse(false), hip: unitHouse(true), broadleaf: unitBroadleaf(), conifer: unitConifer(), palm: unitPalm() };
    this.override = null;
    this.nightFactor = 0;
    this.lightsFactor = 0;
    this.sunEl = 30;
    this.stats = {};
    this._camW = new THREE.Vector3();
    this._q = new THREE.Quaternion();

    const mk = (name, kind, builder) => {
      const group = new THREE.Group();
      group.name = name;
      app.worldRoot.add(group);
      return { name, kind, group, land: new Land(app, kind), builder, objects: [], job: null, built: false, dirty: true, update: null, traffic: null };
    };
    this.departure = mk('city.departure', 'departure', buildDeparture);
    this.arrival = mk('city.arrival', 'arrival', buildArrival);

    this.enroute = new EnRoute(app, this.mats.points);
    // we start at the departure gate: build it now
    this._buildSync(this.departure);

    app.events.on('world:arrivalMoved', () => { this.arrival.dirty = true; this._cancel(this.arrival); });
    app.events.on('quality:changed', (q) => {
      const d = clamp(q?.detail ?? app.quality?.detail ?? 1, 0, 3);
      if (d === this.detail) return;
      this.detail = d;
      for (const R of [this.departure, this.arrival]) { R.dirty = true; this._cancel(R); }
    });
    app.addUpdate((dt) => this.update(dt), 65, 'city');
    this.update(0);
  }

  // ------------------------------------------------------------------ building
  _ctx(R) {
    R.land.sync();
    return { app: this.app, land: R.land, detail: this.detail, mats: this.mats, unit: this.unit };
  }
  _start(R) {
    R.land.sync();
    R.group.position.set(R.land.ax, 0, R.land.az);
    R.job = { gen: R.builder(this._ctx(R)), t0: performance.now(), anchor: [R.land.ax, R.land.az] };
    R.dirty = false;
  }
  _cancel(R) { R.job = null; }
  _step(R, budgetMs) {
    const t0 = performance.now();
    try {
      while (performance.now() - t0 < budgetMs) {
        const res = R.job.gen.next();
        if (res.done) { this._finish(R, res.value); return true; }
      }
    } catch (e) {
      console.error(`[city] building ${R.name} failed`, e);
      R.job = null; R.built = false; R.dirty = false;
      return true;
    }
    return false;
  }
  _buildSync(R) {
    this._start(R);
    this._step(R, 1e9);
  }
  _finish(R, result) {
    const ms = performance.now() - R.job.t0;
    R.job = null;
    // replace content
    for (const o of R.objects) {
      R.group.remove(o);
      o.geometry?.dispose?.();
    }
    R.traffic?.dispose?.();
    R.objects = result?.objects || [];
    R.traffic = result?.traffic || null;
    R.update = result?.update || null;
    for (const o of R.objects) { o.updateMatrix?.(); R.group.add(o); }
    R.shadows = R.objects.filter((o) => o.userData?.isShadow);
    R.group.updateMatrixWorld(true);
    R.built = true;
    this.stats[R.kind] = { ...(result?.stats || {}), buildMs: Math.round(ms), drawObjects: R.objects.length };
    if (this.app.debug?.module === 'city-stats') console.log(`[city] ${R.kind} built in ${ms.toFixed(0)} ms`, this.stats[R.kind]);
  }

  // ------------------------------------------------------------------ frame
  update(dt) {
    const app = this.app;
    const U = CITY_U;
    // camera & up in scene (aircraft-local) space
    U.uCamPos.value.copy(app.camera.position);
    this._q.copy(app.flight.state.quaternion).invert();
    U.uUp.value.set(0, 1, 0).applyQuaternion(this._q);
    const H = app.pipeline?.height || window.innerHeight || 720;
    U.uPx.value = H / (2 * Math.tan((app.camera.fov || 60) * DEG / 2));
    U.uFogD.value = app.scenes.outside.fog?.density ?? 0.00005;
    U.uTime.value = app.time % 3600;
    U.uDetail.value = this.detail;

    // day / night
    const env = app.environment;
    let el = env && Number.isFinite(env.sunElevationDeg) ? env.sunElevationDeg : null;
    if (el === null) {
      const d = app.sun?.direction;
      el = d ? Math.asin(clamp(d.y, -1, 1)) / DEG : 30;
      if ((app.sun?.intensity ?? 1) < 0.02) el = Math.min(el, -8);
    }
    this.sunEl = el;
    let night = env && Number.isFinite(env.nightFactor) ? env.nightFactor : sstep(-3, -11, el);
    if (this.override !== null) night = this.override;
    this.nightFactor = night;
    // street lights switch on around sunset (photocells), windows fill up through dusk
    const lights = this.override !== null ? sstep(0.0, 0.25, this.override) : sstep(3.5, -1.5, el);
    this.lightsFactor = lights;
    U.uLights.value = lights;
    U.uWin.value = 0.3 + 0.7 * (this.override !== null ? this.override : sstep(5, -9, el));
    U.uWinE.value = 0.2 + 0.2 * sstep(0, -10, el);

    // projected shadows: direct-sun share of the ground irradiance, tinted by the sky
    const sd = env?.sunDirection || app.sun.direction;
    const shadowOn = el > 0.6 && this.detail >= 1;
    if (shadowOn) {
      const Ly = Math.max(sd.y, 0.07);
      const hl = Math.hypot(sd.x, sd.z) || 1;
      const k = Math.sqrt(Math.max(0, 1 - Ly * Ly)) / hl;
      SHADOW_U.uSunL.value.set(sd.x * k, Ly, sd.z * k);
      const s = app.sun;
      const Es = (s.intensity || 0) * Math.max(0, sd.y), Ea = Math.max(1e-4, s.ambientIntensity || 0.5);
      const sc = s.color, kc = s.skyColor;
      const ch = (a, b) => { const lit = Es * a + Ea * b; const sh = Ea * b + 0.08 * Es * a; return lit > 1e-6 ? sh / lit : 1; };
      const fade = sstep(0.6, 3.0, el);
      const f = (v) => 1 - (1 - Math.max(0.42, Math.min(1, v))) * fade;
      SHADOW_U.uShadowMul.value.set(f(ch(sc.r, kc.r)), f(ch(sc.g, kc.g)), f(ch(sc.b, kc.b)));
    }
    this.shadowOn = shadowOn;

    // en-route town lights (only when lights are on)
    this.enroute.group.visible = lights > 0.01;
    if (lights > 0.01) { try { this.enroute.update(); } catch (e) { console.error('[city] en-route lights failed', e); this.enroute.update = () => {}; } }

    // region visibility + lazy (re)builds
    app.world.toWorld(app.camera.position, this._camW);
    for (const R of [this.departure, this.arrival]) {
      const ax = R.kind === 'arrival' ? app.world.arrivalOrigin.x : app.world.departureOrigin.x;
      const az = R.kind === 'arrival' ? app.world.arrivalOrigin.z : app.world.departureOrigin.z;
      const dist = Math.hypot(this._camW.x - ax, this._camW.z - az);
      const want = dist < 160000;
      if (R.dirty && want && !R.job) this._start(R);
      if (R.job) {
        // finish immediately when close (or on the very first frames), otherwise a few ms per frame
        const urgent = dist < 30000 || !app.ready;
        this._step(R, urgent ? 1e9 : 5);
      }
      R.group.visible = R.built && dist < 90000 && !R.job;
      if (R.shadows) for (const m of R.shadows) m.visible = shadowOn && dist < 40000;
      if (R.group.visible && R.update) {
        try { R.update(dt, app.time); } catch (e) { console.error('[city] region update failed', e); R.update = null; }
      }
    }
  }

  get api() {
    const city = this;
    return {
      departure: { get group() { return city.departure.group; } },
      arrival: { get group() { return city.arrival.group; } },
      /** 0 = day ... 1 = full night (from the environment, or the override). */
      get nightFactor() { return city.nightFactor; },
      /** 0..1 street lights on. */
      get lightsFactor() { return city.lightsFactor; },
      /** Force the night factor (0..1) or null to follow the sun. */
      setNightFactor(v) { city.override = (v === null || v === undefined) ? null : clamp(Number(v), 0, 1); },
      /** Rebuild both regions (e.g. after geography changes). */
      rebuild() { for (const R of [city.departure, city.arrival]) { R.dirty = true; city._cancel(R); } },
      get stats() { return city.stats; },
      get ready() { return city.departure.built && (city.arrival.built || city.arrival.dirty); },
      uniforms: CITY_U,
    };
  }
}

export async function init(app) {
  const city = new City(app);
  return city.api;
}
