const canvasCache = new Map();
const urlCache = new Map();

function expand(def) {
  let rows = def;
  let outline = true;
  if (!Array.isArray(def)) {
    rows = def.m ? mir(def.rows) : def.rows;
    if (def.outline === false) outline = false;
  }
  return { rows, outline };
}

/** Draw a pixel map into a canvas (1 px per cell). opts: {outline, tint, outlineColor} */
export function pixelCanvas(name, opts = {}) {
  const key = name + '|' + (opts.tint || '') + '|' + (opts.outline ?? '') + '|' + (opts.outlineColor || '');
  if (canvasCache.has(key)) return canvasCache.get(key);
  const def = PIXEL_ICONS[name] || PIXEL_ICONS.unknown;
  const { rows, outline: defOutline } = expand(def);
  const isSil = name.startsWith('eq_');
  const outline = opts.outline ?? (isSil ? false : defOutline);
  const H = rows.length;
  const W = Math.max(...rows.map((r) => r.length));
  const pad = outline ? 1 : 0;
  const c = document.createElement('canvas');
  c.width = W + pad * 2;
  c.height = H + pad * 2;
  const g = c.getContext('2d');
  const filled = (x, y) => y >= 0 && y < H && x >= 0 && x < W && rows[y][x] && rows[y][x] !== '.';
  if (outline) {
    g.fillStyle = opts.outlineColor || PAL.k;
    for (let y = -1; y <= H; y++) {
      for (let x = -1; x <= W; x++) {
        if (filled(x, y)) continue;
        let n = false;
        for (let dy = -1; dy <= 1 && !n; dy++) for (let dx = -1; dx <= 1; dx++) {
          if ((dx || dy) && Math.abs(dx) + Math.abs(dy) === 1 && filled(x + dx, y + dy)) { n = true; break; }
        }
        if (n) g.fillRect(x + pad, y + pad, 1, 1);
      }
    }
  }
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const ch = rows[y][x];
      if (!ch || ch === '.') continue;
      g.fillStyle = opts.tint || PAL[ch] || '#f0f';
      g.fillRect(x + pad, y + pad, 1, 1);
    }
  }
  canvasCache.set(key, c);
  return c;
}

export function pixelURL(name, opts = {}) {
  const key = name + '|' + JSON.stringify(opts);
  if (!urlCache.has(key)) urlCache.set(key, pixelCanvas(name, opts).toDataURL());
  return urlCache.get(key);
}

/** <img> element of a pixel icon (CSS class `px`, pixelated). */
export function pixelImg(name, cls = '', opts) {
  const img = document.createElement('img');
  img.className = 'px ' + cls;
  img.src = pixelURL(name, opts);
  img.alt = '';
  img.draggable = false;
  return img;
}

