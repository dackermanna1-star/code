def helm(t):
    return astro_point(t, (0, 0.03, 1.71))


def torso(t):
    return astro_point(t, (0, 0, 1.2))


def shake(t, amp, seed, freq=1.4):
    if amp <= 0:
        return V(0, 0, 0)
    return V(noise.noise(V(t * freq, seed, 0.0)), noise.noise(V(t * freq, seed + 9.1, 3.3)),
             noise.noise(V(t * freq, seed + 4.7, 7.7))) * amp


def shot_A(t):    # establishing: deep space, tiny planet
    u = ease_io((t - 0.0) / 8.4)
    loc = V(-27, -40, 10).lerp(V(-16.5, -25, 6.6), u)
    tgt = V(3.5, 4.0, 1.4).lerp(V(1.6, 1.4, 3.1), u)
    return loc, tgt, 0.05 - 0.03 * u, 0.0


def shot_B(t):    # low tracking shot in front of the walking astronaut
    u = ease_io((t - 8.0) / 7.2)
    loc = V(1.25, 3.0, R + 0.05).lerp(V(2.6, 1.7, R + 0.45), u)
    tgt = V(0, 0, R + 1.15)
    return loc, tgt, -0.04, 0.0


def shot_C(t):    # side profile on the curvature of the planet, back-lit
    u = ease_io((t - 15.0) / 7.2)
    loc = V(12.5, -3.4, 6.9).lerp(V(11.5, 1.2, 6.2), u)
    tgt = V(0, 0.2, 5.4).lerp(V(0, 0.6, 5.9), u)
    return loc, tgt, 0.02, 0.0


def shot_D(t):    # over the shoulder: the black hole opens in the sky
    u = ease_io((t - 22.0) / 8.0)
    loc = V(0.75, -2.7, R + 0.75).lerp(V(0.5, -2.1, R + 0.95), u)
    look = sstep(22.3, 27.5, t)
    tgt = V(0, 0, R + 1.6).lerp(V(0, 30.0, R + 6.2), look)
    return loc, tgt, -0.02 + 0.04 * u, 0.012 * sstep(27.0, 30.0, t)


def shot_E(t):    # visor close-up, the disk reflected in the gold visor
    u = ease_io((t - 30.0) / 6.0)
    h = helm(t)
    loc = h + V(0.5, 1.35, -0.12).lerp(V(0.32, 1.05, -0.02), u)
    tgt = h + V(0.0, 0.0, -0.04)
    return loc, tgt, 0.03, 0.02 + 0.02 * sstep(30.5, 33.0, t) - 0.015 * sstep(34.0, 36.0, t)


def aim(loc, pts_w):
    """aim direction that balances several world points (point, weight)"""
    d = V(0, 0, 0)
    for p, w in pts_w:
        d += (p - loc).normalized() * w
    return loc + d.normalized() * 50.0


def shot_F(t):    # grand wide: the planet is torn apart and streams into the disk
    u = ease_io((t - 36.0) / 10.0)
    loc = V(-27, -52, 12).lerp(V(-21, -41, 9.5), u)
    stream = V(0, 0, 0).lerp(V(0, 18, 4), u)
    tgt = aim(loc, [(stream, 0.56), (BH_POS, 0.44)])
    return loc, tgt, -0.05 + 0.02 * u, 0.05


def shot_G(t):    # tracking the tumbling astronaut through the debris stream
    u = ease_io((t - 46.0) / 8.0)
    a = lerp(-2.35, -1.5, u)
    c = torso(t)
    loc = c + V(4.2 * math.cos(a), 4.2 * math.sin(a), 1.1 - 0.5 * u)
    tgt = aim(loc, [(c, 0.66), (BH_POS, 0.34)])
    return loc, tgt, 0.05 - 0.1 * u, 0.025


def shot_H(t):    # finale: falling towards the accretion disk
    u = clamp((t - 54.0) / 6.0)
    c = torso(t)
    off = V(1.0, -6.8, 1.8).lerp(V(0.5, -2.4, 1.05), u * u)
    loc = c + off
    tgt = (c + V(0, 4.0, 0.8)).lerp(BH_POS, sstep(0.15, 0.9, u))
    return loc, tgt, 0.0 + 0.45 * u * u, 0.02 + 0.10 * u * u


