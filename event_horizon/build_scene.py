print("Collision avoidance ...")
OBSTACLES = []
for cam, frames, locs in CAMS:
    OBSTACLES.append((cam.name, list(zip(frames[::2], locs[::2])), 1.0))
OBSTACLES.append(("astronaut", [(f, torso(tm(f))) for f in FRAMES[::2]], 1.5))


def conflict(b):
    big = b.ob.name.startswith(("Chunk", "Core"))
    for name, pts, base in OBSTACLES:
        rad = (2.8 if big else 0.5 + 1.6 * b.scale0) * base
        if b.ob.name.startswith("Core"):
            rad = 11.0
        for f, pos in pts:
            t = tm(f)
            if t < 27.0 and name == "astronaut":
                continue
            if b.t_sw is not None and t > b.t_sw:
                break
            if b.pre is None and t < b.t_rel + 0.5:
                continue
            bp = b.world_pos(t)
            if (bp - pos).length < rad:
                return name, t, bp, pos, rad
    return None


n_fixed = 0
for b in BODIES:
    if b.ob.name.startswith("Pebble"):
        continue
    for attempt in range(10):
        c = conflict(b)
        if c is None:
            break
        name, t, bp, pos, rad = c
        if t < b.t_rel and b.pre is not None:
            b.ob.hide_render = True      # an orbiting pebble that would graze a lens
            break
        away = bp - pos
        away -= U_BH * away.dot(U_BH)
        if away.length < 1e-3:
            away = V(1, 0, 0)
        dt_ = max(0.8, t - b.t_rel)
        b.v0 += away.normalized() * (1.4 * rad / dt_)
        b.run()
        n_fixed += 1
    else:
        print("  could not clear", b.ob.name, c[0], "t=%.1f" % c[1])
print("  %d trajectory corrections" % n_fixed)
for b in BODIES:
    b.bake()

