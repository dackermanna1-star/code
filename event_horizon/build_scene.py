def add_boulder(bm, center, normal, size, depth_layer, pid_layer):
    mat = Matrix.Translation(center - normal * size * 0.35)
    res = bmesh.ops.create_icosphere(bm, subdivisions=2, radius=size, matrix=mat)
    seed = V(random.random() * 50, random.random() * 50, random.random() * 50)
    flat = random.uniform(0.55, 0.85)
    for v in res["verts"]:
        rel = v.co - center
        rel *= 1.0 + 0.32 * noise.noise(rel / size * 1.3 + seed)
        # flatten along the ground normal
        rel -= normal * rel.dot(normal) * (1 - flat)
        v.co = center + rel
        v[depth_layer] = 0.0
        v[pid_layer] = -1
    faces = set()
    for v in res["verts"]:
        faces.update(v.link_faces)
    for f in faces:
        f.material_index = 0
        f.smooth = True


