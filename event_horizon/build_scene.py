ATMO_R = R * 1.6
ATMO_H = 0.45       # scale height of the haze (m)


def atmosphere_material():
    """Atmospheric haze without a (slow) volume: on the shell, compute the view
    ray's impact parameter b = |P x I| (closest approach to the planet centre)
    and use an exponential atmosphere optical depth exp(-(b-R)/H). This gives a
    soft limb glow that vanishes at the shell edge, haze over the planet's rim,
    and haze towards the horizon when the camera stands on the surface."""
    m, nt, out = new_mat("Atmosphere")
    dens = VALUE(nt, "density", 1.0)
    inside = VALUE(nt, "cam_inside", 0.0)
    geo = nnew(nt, "ShaderNodeNewGeometry")
    P, I = geo.outputs["Position"], geo.outputs["Incoming"]
    b = VM(nt, "LENGTH", VM(nt, "CROSS_PRODUCT", P, I))
    tau = M(nt, "EXPONENT", M(nt, "DIVIDE", M(nt, "MAXIMUM", M(nt, "SUBTRACT", b, R + 0.1), 0.0), -ATMO_H))
    over_disk = MR(nt, M(nt, "POWER", M(nt, "DIVIDE", b, R + 0.1), 8.0), 0.0, 1.0, 0.05, 1.0)
    closest = VM(nt, "SUBTRACT", P, VM(nt, "SCALE", I, scale=VM(nt, "DOT_PRODUCT", P, I)))
    sun_f = MR(nt, VM(nt, "DOT_PRODUCT", VM(nt, "NORMALIZE", closest), tuple(SUN_DIR)), -0.35, 0.7, 0.08, 1.0,
               smooth=True)
    # only the first crossing of the shell counts (front face from outside, back face from inside)
    first = M(nt, "SUBTRACT", 1.0, M(nt, "ABSOLUTE", M(nt, "SUBTRACT", geo.outputs["Backfacing"], inside.outputs[0])))
    alpha = M(nt, "MULTIPLY", M(nt, "MULTIPLY", tau, over_disk), M(nt, "MULTIPLY", first, dens.outputs[0]))
    alpha = M(nt, "MINIMUM", M(nt, "MULTIPLY", alpha, 0.38), 0.5)
    em = nnew(nt, "ShaderNodeEmission")
    put(nt, em.inputs["Color"], (0.34, 0.44, 0.62, 1))
    put(nt, em.inputs["Strength"], M(nt, "MULTIPLY", sun_f, 0.75))
    mix = nnew(nt, "ShaderNodeMixShader")
    put(nt, mix.inputs[0], alpha)
    nt.links.new(nnew(nt, "ShaderNodeBsdfTransparent").outputs[0], mix.inputs[1])
    nt.links.new(em.outputs[0], mix.inputs[2])
    nt.links.new(mix.outputs[0], out.inputs["Surface"])
    m.cycles.emission_sampling = "NONE"
    return m


