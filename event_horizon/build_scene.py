def rock_material():
    m, nt, out = new_mat("Rock_Crust")
    attr = nnew(nt, "ShaderNodeAttribute", attribute_name="orig")
    vec = attr.outputs["Vector"]
    n1 = NOISE(nt, vec, 0.9, 12.0, 0.62, 0.15)
    n2 = NOISE(nt, vec, 7.0, 8.0, 0.6)
    vor = VORONOI(nt, vec, 4.0)
    mix = M(nt, "ADD", n1.outputs["Fac"], M(nt, "MULTIPLY", n2.outputs["Fac"], 0.22))
    col = RAMP(nt, mix, [(0.40, (0.030, 0.027, 0.025)),
                         (0.52, (0.105, 0.092, 0.080)),
                         (0.62, (0.215, 0.190, 0.165)),
                         (0.72, (0.330, 0.300, 0.270))])
    rough = MR(nt, n2.outputs["Fac"], 0.3, 0.7, 0.75, 0.95)
    hgt = M(nt, "ADD", M(nt, "MULTIPLY", n2.outputs["Fac"], 0.6),
            M(nt, "MULTIPLY", vor.outputs["Distance"], 0.5))
    bump = nnew(nt, "ShaderNodeBump")
    put(nt, bump.inputs["Strength"], 0.45)
    put(nt, bump.inputs["Distance"], 0.08)
    put(nt, bump.inputs["Height"], hgt)
    p = principled(nt, **{"Base Color": col, "Roughness": rough,
                          "Specular IOR Level": 0.3, "Normal": bump.outputs[0]})
    # low-lying haze: camera rays fade into the fog colour with distance
    haze = VALUE(nt, "haze", 1.0)
    lp = nnew(nt, "ShaderNodeLightPath")
    fogf = M(nt, "SUBTRACT", 1.0, M(nt, "EXPONENT", M(nt, "MULTIPLY", lp.outputs["Ray Length"], -0.06)))
    fogf = M(nt, "MULTIPLY", M(nt, "MULTIPLY", fogf, lp.outputs["Is Camera Ray"]), haze.outputs[0])
    geo = nnew(nt, "ShaderNodeNewGeometry")
    lit = MR(nt, VM(nt, "DOT_PRODUCT", VM(nt, "NORMALIZE", geo.outputs["Position"]), tuple(SUN_DIR)),
             -0.3, 0.7, 0.05, 1.0, smooth=True)
    fe = nnew(nt, "ShaderNodeEmission")
    put(nt, fe.inputs["Color"], (0.30, 0.36, 0.48, 1))
    put(nt, fe.inputs["Strength"], M(nt, "MULTIPLY", lit, 0.55))
    mix = nnew(nt, "ShaderNodeMixShader")
    put(nt, mix.inputs[0], M(nt, "MULTIPLY", fogf, 0.75))
    nt.links.new(p.outputs[0], mix.inputs[1])
    nt.links.new(fe.outputs[0], mix.inputs[2])
    nt.links.new(mix.outputs[0], out.inputs["Surface"])
    m.cycles.emission_sampling = "NONE"
    return m


def interior_material():
    m, nt, out = new_mat("Rock_Interior")
    glow = VALUE(nt, "glow", 0.0)
    depth = nnew(nt, "ShaderNodeAttribute", attribute_name="depth").outputs["Fac"]
    vec = nnew(nt, "ShaderNodeAttribute", attribute_name="orig").outputs["Vector"]
    n1 = NOISE(nt, vec, 3.0, 10.0, 0.65, 0.4)
    vor = VORONOI(nt, vec, 2.5, feature="DISTANCE_TO_EDGE")
    cracks = MR(nt, vor.outputs["Distance"], 0.0, 0.08, 1.0, 0.0, smooth=True)
    col = RAMP(nt, n1.outputs["Fac"], [(0.35, (0.035, 0.025, 0.022)),
                                       (0.65, (0.12, 0.08, 0.06))])
    heat = M(nt, "POWER", depth, 1.6)
    heat = M(nt, "MULTIPLY", heat, M(nt, "ADD", 0.35, M(nt, "MULTIPLY", cracks, 1.6)))
    strength = M(nt, "MULTIPLY", M(nt, "MULTIPLY", heat, glow.outputs[0]), 14.0)
    ecol = RAMP(nt, depth, [(0.2, (0.6, 0.06, 0.01)), (0.7, (1.0, 0.32, 0.05)),
                            (1.0, (1.0, 0.62, 0.22))])
    bump = nnew(nt, "ShaderNodeBump")
    put(nt, bump.inputs["Strength"], 0.6)
    put(nt, bump.inputs["Height"], n1.outputs["Fac"])
    p = principled(nt, **{"Base Color": col, "Roughness": 0.92,
                          "Emission Color": ecol, "Emission Strength": strength,
                          "Normal": bump.outputs[0]})
    nt.links.new(p.outputs[0], out.inputs["Surface"])
    m.cycles.emission_sampling = "NONE"
    return m


