def nnew(nt, kind, **props):
    n = nt.nodes.new(kind)
    for k, v in props.items():
        setattr(n, k, v)
    return n


def put(nt, sock, val):
    if isinstance(val, bpy.types.NodeSocket):
        nt.links.new(val, sock)
    elif val is not None:
        sock.default_value = val


def M(nt, op, a, b=None, c=None, use_clamp=False):
    n = nnew(nt, "ShaderNodeMath", operation=op, use_clamp=use_clamp)
    put(nt, n.inputs[0], a)
    if b is not None:
        put(nt, n.inputs[1], b)
    if c is not None:
        put(nt, n.inputs[2], c)
    return n.outputs[0]


def VM(nt, op, a, b=None, scale=None):
    n = nnew(nt, "ShaderNodeVectorMath", operation=op)
    put(nt, n.inputs[0], a)
    if b is not None:
        put(nt, n.inputs[1], b)
    if scale is not None:
        put(nt, n.inputs["Scale"], scale)
    out = "Value" if op in ("LENGTH", "DOT_PRODUCT", "DISTANCE") else "Vector"
    return n.outputs[out]


def MR(nt, val, fmin, fmax, tmin, tmax, smooth=False, use_clamp=True):
    n = nnew(nt, "ShaderNodeMapRange", clamp=use_clamp)
    if smooth:
        n.interpolation_type = "SMOOTHSTEP"
    put(nt, n.inputs[0], val)
    put(nt, n.inputs[1], fmin)
    put(nt, n.inputs[2], fmax)
    put(nt, n.inputs[3], tmin)
    put(nt, n.inputs[4], tmax)
    return n.outputs[0]


def RAMP(nt, fac, stops):
    n = nnew(nt, "ShaderNodeValToRGB")
    els = n.color_ramp.elements
    while len(els) > 1:
        els.remove(els[-1])
    els[0].position = stops[0][0]
    els[0].color = (*stops[0][1], 1.0)
    for pos, col in stops[1:]:
        e = els.new(pos)
        e.color = (*col, 1.0)
    put(nt, n.inputs[0], fac)
    return n.outputs[0]


def NOISE(nt, vec, scale, detail=4.0, rough=0.5, dist=0.0, w=None, dims="3D"):
    n = nnew(nt, "ShaderNodeTexNoise")
    n.noise_dimensions = "4D" if w is not None else dims
    put(nt, n.inputs["Vector"], vec)
    put(nt, n.inputs["Scale"], scale)
    put(nt, n.inputs["Detail"], detail)
    put(nt, n.inputs["Roughness"], rough)
    put(nt, n.inputs["Distortion"], dist)
    if w is not None:
        put(nt, n.inputs["W"], w)
    return n


def VORONOI(nt, vec, scale, feature="F1"):
    n = nnew(nt, "ShaderNodeTexVoronoi", voronoi_dimensions="3D", feature=feature)
    put(nt, n.inputs["Vector"], vec)
    put(nt, n.inputs["Scale"], scale)
    put(nt, n.inputs["Randomness"], 1.0)
    return n


def VALUE(nt, name, v=0.0):
    n = nnew(nt, "ShaderNodeValue", name=name, label=name)
    n.outputs[0].default_value = v
    return n


def value_path(name):
    return 'nodes["%s"].outputs[0].default_value' % name


def new_mat(name):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nnew(nt, "ShaderNodeOutputMaterial")
    return m, nt, out


def principled(nt, **kw):
    p = nnew(nt, "ShaderNodeBsdfPrincipled")
    for k, v in kw.items():
        put(nt, p.inputs[k], v)
    return p


def simple_mat(name, color, rough=0.5, metal=0.0, **kw):
    m, nt, out = new_mat(name)
    p = principled(nt, **{"Base Color": (*color, 1), "Roughness": rough, "Metallic": metal}, **kw)
    nt.links.new(p.outputs[0], out.inputs["Surface"])
    return m, nt, p, out


