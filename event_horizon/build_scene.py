def fbm(p, octaves, lac=2.0, gain=0.5):
    s, a, f, norm = 0.0, 1.0, 1.0, 0.0
    for _ in range(octaves):
        s += a * noise.noise(p * f, noise_basis="PERLIN_ORIGINAL")
        norm += a
        a *= gain
        f *= lac
    return s / norm


CRATERS = []
while len(CRATERS) < 26:
    d = V(random.gauss(0, 1), random.gauss(0, 1), random.gauss(0, 1)).normalized()
    ca = random.uniform(0.09, 0.36)
    if abs(d.x) < ca + 0.10:          # keep the walking path clear
        continue
    CRATERS.append((d, ca, random.uniform(0.25, 0.7) * ca))


def height(d):
    base = 0.20 * fbm(d * 1.4, 2)
    h = 0.20 * fbm(d * 1.4, 5) - base + 0.045 * fbm(d * 6.0 + V(3, 1, 7), 3)
    for cd, ca, depth in CRATERS:
        ang = math.acos(clamp(d.dot(cd), -1.0, 1.0))
        x = ang / ca
        if x < 2.2:
            rim = 0.32 * math.exp(-((x - 1.0) / 0.24) ** 2)
            h += depth * ((x * x - 1.0) + rim if x < 1.0 else rim)
    m = sstep(0.025, 0.20, abs(d.x))     # smoother trail along the great circle x=0
    return base + h * (0.18 + 0.82 * m)


