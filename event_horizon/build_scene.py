def accel(p, t, t_rel, tidal):
    d = BH_POS - p
    r = d.length
    a = d * (K_GRAV / (r * r * r))
    if tidal > 0:
        off = p.copy()
        along = off.dot(U_BH)
        perp = off - U_BH * along
        a += (U_BH * (2.0 * along) + perp * 0.3) * (tidal * math.exp(-(t - t_rel) / 2.6))
    return a


def simulate(p0, v0, t_rel, tidal, dt=1.0 / 48.0):
    """returns times, positions, swallow time"""
    ts, ps = [t_rel], [p0.copy()]
    p, v, t = p0.copy(), v0.copy(), t_rel
    t_sw = None
    while t < DURATION + 0.2:
        v += accel(p, t, t_rel, tidal) * dt
        p += v * dt
        t += dt
        ts.append(t)
        ps.append(p.copy())
        if t_sw is None and (p - BH_POS).length < RH * 2.4:
            t_sw = t
    return ts, ps, t_sw


def sample(ts, ps, t):
    if t <= ts[0]:
        return ps[0]
    k = (t - ts[0]) / (ts[1] - ts[0])
    i = min(int(k), len(ps) - 2)
    return ps[i].lerp(ps[i + 1], k - i)


class Body:
    def __init__(self, ob, parented, p_world, t_rel, v0, tidal, crack=0.0, spin_rate=0.4,
                 pre=None, rot0=None, scale0=1.0, stretch=False):
        self.ob, self.parented, self.p0, self.t_rel = ob, parented, p_world, t_rel
        self.v0, self.tidal, self.crack = v0, tidal, crack
        self.axis = V(random.gauss(0, 1), random.gauss(0, 1), random.gauss(0, 1)).normalized()
        self.spin_rate = spin_rate
        self.pre = pre                # optional function t -> world pos before release
        self.rot0 = rot0 or Euler((0, 0, 0))
        self.scale0 = scale0
        self.stretch = stretch
        self.seed = random.random() * 100

    def run(self):
        p_rel = self.pre(self.t_rel) if self.pre else self.p0
        self.ts, self.ps, self.t_sw = simulate(p_rel, self.v0, self.t_rel, self.tidal)

    def world_pos(self, t):
        if t < self.t_rel:
            if self.pre:
                return self.pre(t)
            p = self.p0.copy()
            if self.crack > 0:
                c = sstep(self.t_rel - 2.6, self.t_rel, t)
                n = self.p0.normalized()
                p += n * (0.09 * c)
                p += noise.noise_vector(V(t * 6.0, self.seed, 0)) * (0.018 * c)
            return p
        return sample(self.ts, self.ps, t)

    def bake(self):
        if self.pre:
            frames = list(range(1, int(fr(self.t_rel)), 6)) + list(range(int(fr(self.t_rel)), NF + 2, 2))
        else:
            start = max(1, int(fr(self.t_rel - (2.8 if self.crack else 0.2))))
            frames = list(range(start, NF + 2, 2))
        locs, rots, scl = [], [], []
        prev = None
        q0 = self.rot0.to_quaternion()
        for f in frames:
            t = tm(f)
            p = self.world_pos(t)
            if self.parented:
                p = RIG_INV_F @ p
            locs.append(p)
            if self.pre:
                ang = self.spin_rate * t
            else:
                tau = max(0.0, t - self.t_rel)
                ang = self.spin_rate * tau * tau / (tau + 1.8)
            e = (Quaternion(self.axis, ang) @ q0).to_euler("XYZ", prev) if prev else \
                (Quaternion(self.axis, ang) @ q0).to_euler("XYZ")
            prev = e
            rots.append(e)
            s = self.scale0
            if self.t_sw is not None:
                s *= 1.0 - sstep(self.t_sw, self.t_sw + 0.4, t)
            sv = V(s, s, s)
            if self.stretch:
                sv.y *= 1.0 + 2.2 * sstep(47.0, 58.0, t)
                sv.x *= 1.0 - 0.3 * sstep(47.0, 58.0, t)
                sv.z *= 1.0 - 0.3 * sstep(47.0, 58.0, t)
            scl.append(sv)
        bake_vec(self.ob, "location", frames, locs)
        bake_vec(self.ob, "rotation_euler", frames, rots)
        if self.t_sw is not None or self.stretch:
            bake_vec(self.ob, "scale", frames, scl)


