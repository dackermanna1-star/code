def fr(t):
    return 1.0 + t * FPS


def tm(f):
    return (f - 1.0) / FPS


def clamp(x, a=0.0, b=1.0):
    return a if x < a else b if x > b else x


def sstep(e0, e1, x):
    u = clamp((x - e0) / (e1 - e0))
    return u * u * (3.0 - 2.0 * u)


def lerp(a, b, u):
    return a + (b - a) * u


def ease_io(u):
    u = clamp(u)
    return u * u * u * (u * (u * 6 - 15) + 10)


def V(*a):
    return Vector(a)


# ---------------------------------------------------------------------------
# Fast keyframe baking
# ---------------------------------------------------------------------------
INTERP = {"CONSTANT": 0, "LINEAR": 1, "BEZIER": 2}


def bake(idb, path, frames, values, index=-1, interp="LINEAR"):
    """Write many keyframes at once on idb.<path>[index]."""
    idb.keyframe_insert(data_path=path, index=index, frame=frames[0])
    ad = idb.animation_data
    # Blender 4.4+ "slotted actions": object and object-data can share one action,
    # so look the F-Curve up in the channelbag of this ID's own slot.
    cbag = anim_utils.action_get_channelbag_for_slot(ad.action, ad.action_slot)
    fc = cbag.fcurves.find(path, index=max(index, 0))
    kp = fc.keyframe_points
    n = len(frames)
    if len(kp) < n:
        kp.add(n - len(kp))
    co = [0.0] * (2 * n)
    co[0::2] = [float(f) for f in frames]
    co[1::2] = [float(v) for v in values]
    kp.foreach_set("co", co)
    kp.foreach_set("interpolation", [INTERP[interp]] * n)
    fc.update()
    return fc


def bake_vec(obj, path, frames, vecs, dims=3, interp="LINEAR"):
    for i in range(dims):
        bake(obj, path, frames, [v[i] for v in vecs], index=i, interp=interp)


def key_curve(idb, path, pts, interp="BEZIER"):
    """pts: list of (time_seconds, value)."""
    bake(idb, path, [fr(t) for t, _ in pts], [v for _, v in pts], interp=interp)


