#!/usr/bin/env python3
"""Generate public/assets/CREDITS.md from the texture and sound manifests.

Usage: python3 -I scripts/assets/write_credits.py
"""
import collections
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
ASSETS = os.path.join(REPO, "public", "assets")


def main():
    tex = json.load(open(os.path.join(ASSETS, "textures", "manifest.json")))
    snd = json.load(open(os.path.join(ASSETS, "sounds", "manifest.json")))
    out = []
    w = out.append
    w("# Asset credits\n")
    w("Every file under `public/assets/` is public domain: either **CC0 1.0 Universal** third-party "
      "material (listed below with its source) or generated for this project and also released as CC0. "
      "No attribution is legally required for CC0 works; it is given here anyway. "
      "All files were re-processed (downscaled / colour-graded / converted); "
      "see `scripts/assets/README.md` for how to regenerate them.\n")
    w("CC0 legal code: https://creativecommons.org/publicdomain/zero/1.0/\n")

    w("## Textures (`public/assets/textures/`)\n")
    w("Photo/PBR sources: [ambientCG](https://ambientcg.com) by Lennart Demes and contributors (CC0). "
      "`sourceMethod` is ambientCG's own creation-method tag (PBRPhotogrammetry / PBRMultiAngle / "
      "PBRApproximated = photo based, PBRProcedural = authored procedurally by ambientCG); "
      "`numpy procedural` textures were generated by `scripts/assets/procedural_textures.py`.\n")
    w("| Texture | Source | Method | License | URL |")
    w("|---|---|---|---|---|")
    for r in tex:
        w("| `%s` | %s | %s | %s | %s |" % (r["name"], r["source"], r.get("sourceMethod", ""), r["license"],
                                          r["url"] or "-"))
    w("")

    w("## Sounds (`public/assets/sounds/`)\n")
    w("All sounds were converted to mono 44.1 kHz OGG Vorbis (q5), trimmed and peak-normalised.\n")
    w("| Folder | Pack | Author | License | URL | Files used |")
    w("|---|---|---|---|---|---|")
    packs = collections.OrderedDict()
    for r in snd:
        packs.setdefault(r["pack"], {"src": r["source"], "license": r["license"], "url": r["url"], "n": 0})
        packs[r["pack"]]["n"] += 1
    for pid, p in packs.items():
        title, _, author = p["src"].rpartition(" (")
        w("| `%s/` | %s | %s | %s | %s | %d |" % (pid, title, author.rstrip(")"), p["license"], p["url"], p["n"]))
    w("")
    with open(os.path.join(ASSETS, "CREDITS.md"), "w") as f:
        f.write("\n".join(out))
    print("wrote", os.path.join(ASSETS, "CREDITS.md"))


if __name__ == "__main__":
    main()
